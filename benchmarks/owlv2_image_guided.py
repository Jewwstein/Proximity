"""OWL-V2 image-guided key-fob detection head-to-head with YOLOE.
Samples generated by benchmarks/yoloe_real_fob.py. Original photos from
Wikimedia Commons; output is an honest benchmark, not a phone demo.
"""
import json,time
from pathlib import Path
import torch
from PIL import Image
from transformers import AutoProcessor, Owlv2ForObjectDetection

root=Path("benchmarks/reports")
ground=json.loads((root/"yoloe-real-key-fob-benchmark.json").read_text()) if (root/"yoloe-real-key-fob-benchmark.json").exists() else None
# Source scene is built by the previous YOLOE benchmark step.
if ground is None:raise FileNotFoundError("Run yoloe_real_fob.py to build the input scene first")
images=[Image.open(root/n).convert("RGB") for n in (
    "real-fob-reference.jpg","real-fob-desk-positive.jpg","desk-negative-no-keys.jpg")]
reference,positive,negative=images
torch.set_num_threads(2)
checkpoint="google/owlv2-base-patch16-ensemble"
print("LOADING",checkpoint,flush=True)
processor=AutoProcessor.from_pretrained(checkpoint)
model=Owlv2ForObjectDetection.from_pretrained(checkpoint).eval()
def run(scene):
    t0=time.perf_counter()
    features=processor(images=scene,query_images=reference,return_tensors="pt")
    with torch.no_grad(): result=model.image_guided_detection(**features)
    outputs=processor.post_process_image_guided_detection(
        outputs=result,threshold=.1,nms_threshold=.4,
        target_sizes=torch.tensor([scene.size[::-1]]))[0]
    prediction=[{"box":[round(float(x),2) for x in b],"score":round(float(s),3)}
        for b,s in zip(outputs["boxes"].tolist(),outputs["scores"].tolist())]
    prediction=sorted(prediction,key=lambda x:-x["score"])
    return prediction,round(time.perf_counter()-t0,2)
pos,first=run(positive)
neg,second=run(negative)
truth=ground["target_truth_box"]
def iou(a,b):
    l=max(a[0],b[0]);t=max(a[1],b[1]);r=min(a[2],b[2]);bottom=min(a[3],b[3])
    overlap=max(0,r-l)*max(0,bottom-t)
    union=(a[2]-a[0])*(a[3]-a[1])+(b[2]-b[0])*(b[3]-b[1])-overlap
    return overlap/union if union>0 else 0
pairs=sorted([(iou(r["box"],truth),r["score"]) for r in pos],reverse=True)
negative_max=max([r["score"] for r in neg],default=0)
pass_gate=bool(any(overlap>=.2 and confidence>negative_max for overlap,confidence in pairs))
result={"model":checkpoint,"category":"image-guided visual reference",
    "input":"Same public-domain photographed key fob among synthetic clutter as YOLOE",
    "best_key_iou":max([v[0] for v in pairs],default=0),
    "best_key_match":pairs[:3],
    "negative_max":negative_max,
    "runtime_cpu_seconds":{"first":first,"subsequent":second},
    "positive_proposals":pos[:18],"negative_proposals":neg[:18],
    "passes_fob_gate":pass_gate,
    "warning":"Composite scene, not a physical camera test. This CPU runtime is not a phone speed benchmark."
}
(root/"owlv2-real-fob-benchmark.json").write_text(json.dumps(result,indent=2))
print("OWL_V2_FOB_TEST",json.dumps({k:v for k,v in result.items() if k not in ("positive_proposals","negative_proposals")}),flush=True)
assert pass_gate, "FAIL: OWLv2 image-guided model did not locate fob while rejecting distractors."
